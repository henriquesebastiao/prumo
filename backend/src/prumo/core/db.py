from collections.abc import Iterator
from datetime import datetime
from functools import lru_cache
from typing import Any, ClassVar
from uuid import UUID, uuid7

from sqlalchemy import DateTime, Engine, ForeignKey, MetaData, create_engine, func
from sqlalchemy.orm import (
    DeclarativeBase,
    Mapped,
    Session,
    declared_attr,
    mapped_column,
    sessionmaker,
)

from prumo.core.clock import utcnow
from prumo.core.config import get_settings

NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    type_annotation_map: ClassVar[dict[Any, Any]] = {datetime: DateTime(timezone=True)}


class IdMixin:
    """UUID v7 primary key, generated by the application."""

    id: Mapped[UUID] = mapped_column(primary_key=True, default=uuid7, sort_order=-100)


class TimestampMixin:
    created_at: Mapped[datetime] = mapped_column(
        default=utcnow, server_default=func.now(), sort_order=100
    )
    updated_at: Mapped[datetime] = mapped_column(
        default=utcnow, onupdate=utcnow, server_default=func.now(), sort_order=101
    )


class UserOwnedMixin:
    """Marks a record as belonging to a user. Every query on it must filter by `user_id`."""

    @declared_attr
    def user_id(cls) -> Mapped[UUID]:
        return mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True, sort_order=-90)


@lru_cache
def get_engine() -> Engine:
    return create_engine(get_settings().database_url, pool_pre_ping=True)


@lru_cache
def get_sessionmaker() -> sessionmaker[Session]:
    return sessionmaker(bind=get_engine(), expire_on_commit=False)


def get_session() -> Iterator[Session]:
    """One session per request. Services commit explicitly; anything left uncommitted is rolled
    back when the session closes."""
    with get_sessionmaker()() as session:
        yield session
